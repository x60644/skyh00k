create table if not exists run_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  league text not null default 'nba',
  status text not null default 'pending',   -- pending | running | done
  picked_up_at timestamptz
);

alter table run_requests enable row level security;

create policy "rr readable" on run_requests for select using (true);
create policy "rr insertable" on run_requests for insert with check (true);
create policy "rr updatable" on run_requests for update using (true);
